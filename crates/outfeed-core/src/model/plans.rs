//! Manifest diffs, SemVer bump types, and release plans.

use serde::{Deserialize, Serialize};

use super::commits::CommitInfo;

/// SemVer bump classification.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum BumpType {
    /// Increments major version (1.0.0 -> 2.0.0).
    Major,
    /// Increments minor version (1.0.0 -> 1.1.0).
    Minor,
    /// Increments patch version (1.0.0 -> 1.0.1).
    Patch,
    /// Increments pre-release patch sequence (0.1.0-beta.2 -> 0.1.0-beta.3).
    PreReleasePatch,
    /// Increments pre-release minor base (0.1.0-beta.2 -> 0.2.0-beta.1).
    PreReleaseMinor,
    /// Increments pre-release alpha sequence (0.1.0-alpha.2 -> 0.1.0-alpha.3).
    PreReleaseAlpha,
}

/// In-memory diff representing planned manifest edits.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ManifestDiff {
    /// File path relative to workspace root.
    pub relative_path: String,
    /// Existing content before edit.
    pub original_content: String,
    /// Planned content after edit.
    pub proposed_content: String,
}

/// Full release proposal generated by outfeed.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReleasePlan {
    /// Target repository name (e.g. "sawhorse").
    pub repo_name: String,
    /// Existing version before release.
    pub current_version: String,
    /// Proposed version after release.
    pub target_version: String,
    /// Category of version bump.
    pub bump_type: BumpType,
    /// Justification explaining why this bump was selected.
    pub bump_rationale: String,
    /// Commits included in this release.
    pub commits: Vec<CommitInfo>,
    /// Storypole ticket keys shipped in this release.
    pub referenced_tickets: Vec<String>,
    /// Rendered Markdown section to be added to CHANGELOG.md.
    pub changelog_markdown: String,
    /// Planned manifest modifications.
    pub manifest_diffs: Vec<ManifestDiff>,
}

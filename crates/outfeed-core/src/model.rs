//! Domain models and data structures for release planning and execution.

use serde::{Deserialize, Serialize};

/// Conventional commit classification.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConventionalKind {
    /// New feature (feat)
    Feat,
    /// Bug fix (fix)
    Fix,
    /// Refactoring (refactor)
    Refactor,
    /// Performance enhancement (perf)
    Perf,
    /// Documentation (docs)
    Docs,
    /// Code style / formatting (style)
    Style,
    /// Chore or maintenance (chore)
    Chore,
    /// Continuous integration (ci)
    Ci,
    /// Build system or dependencies (build)
    Build,
    /// Test suite (test)
    Test,
    /// Other / unrecognized kind
    Other(String),
}

/// Parsed git commit metadata.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CommitInfo {
    /// Short or full git commit SHA.
    pub sha: String,
    /// Raw commit summary line.
    pub summary: String,
    /// Optional commit body.
    pub body: Option<String>,
    /// Conventional commit kind.
    pub kind: ConventionalKind,
    /// Optional scope (e.g. "sawhorse-core").
    pub scope: Option<String>,
    /// Whether commit introduces breaking API or contract change.
    pub is_breaking: bool,
    /// Breaking change description if present.
    pub breaking_description: Option<String>,
    /// Referenced Storypole ticket keys (e.g. ["GB-41", "GB-45"]).
    pub referenced_tickets: Vec<String>,
}

/// SemVer bump classification.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum BumpType {
    /// Increments major version (1.0.0 -> 2.0.0).
    Major,
    /// Increments minor version (1.0.0 -> 1.1.0).
    Minor,
    /// Increments patch version (1.0.0 -> 1.0.1).
    Patch,
    /// Increments pre-release patch sequence (0.1.0-beta.2 -> 0.1.0-beta.3).
    PreReleasePatch,
    /// Increments pre-release minor base (0.1.0-beta.2 -> 0.2.0-beta.1).
    PreReleaseMinor,
    /// Increments pre-release alpha sequence (0.1.0-alpha.2 -> 0.1.0-alpha.3).
    PreReleaseAlpha,
}

/// In-memory diff representing planned manifest edits.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ManifestDiff {
    /// File path relative to workspace root.
    pub relative_path: String,
    /// Existing content before edit.
    pub original_content: String,
    /// Planned content after edit.
    pub proposed_content: String,
}

/// Full release proposal generated by outfeed.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReleasePlan {
    /// Target repository name (e.g. "sawhorse").
    pub repo_name: String,
    /// Existing version before release.
    pub current_version: String,
    /// Proposed version after release.
    pub target_version: String,
    /// Category of version bump.
    pub bump_type: BumpType,
    /// Justification explaining why this bump was selected.
    pub bump_rationale: String,
    /// Commits included in this release.
    pub commits: Vec<CommitInfo>,
    /// Storypole ticket keys shipped in this release.
    pub referenced_tickets: Vec<String>,
    /// Rendered Markdown section to be added to CHANGELOG.md.
    pub changelog_markdown: String,
    /// Planned manifest modifications.
    pub manifest_diffs: Vec<ManifestDiff>,
}

/// Options controlling CLI binary installation.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct InstallOpts {
    /// Build with debug profile instead of release.
    pub debug: bool,
    /// Force rebuild/reinstall even if versions match.
    pub force: bool,
}

/// Options controlling git remote push.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PushOpts {
    /// Git remote name (defaults to "origin").
    pub remote: String,
    /// Simulate without pushing to remote.
    pub dry_run: bool,
}

impl Default for PushOpts {
    fn default() -> Self {
        Self {
            remote: "origin".to_string(),
            dry_run: false,
        }
    }
}

/// Options controlling crates.io publishing.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PublishOpts {
    /// Target registry (defaults to crates.io).
    pub registry: Option<String>,
    /// Simulate publication without uploading.
    pub dry_run: bool,
    /// Delay in seconds between intra-repo dependent crates.
    pub delay_secs: u64,
}

impl Default for PublishOpts {
    fn default() -> Self {
        Self {
            registry: None,
            dry_run: false,
            delay_secs: 15,
        }
    }
}

/// Options controlling the orchestrated release macro.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct ReleaseOpts {
    /// Simulate release without modifying disk or pushing.
    pub dry_run: bool,
    /// Skip installing binary locally.
    pub skip_install: bool,
    /// Skip pushing commits and tags to remote.
    pub skip_push: bool,
    /// Skip publishing crates to registry.
    pub skip_publish: bool,
}

/// Breakdown of disk usage across target directories.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct DiskUsage {
    /// Bytes occupied by debug artifacts (target/debug).
    pub debug_bytes: u64,
    /// Bytes occupied by release artifacts (target/release).
    pub release_bytes: u64,
    /// Bytes occupied by documentation artifacts (target/doc).
    pub doc_bytes: u64,
    /// Other target bytes.
    pub other_bytes: u64,
    /// Total target bytes.
    pub total_bytes: u64,
}

/// Options controlling workspace cache cleaning.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct CleanOpts {
    /// Full target clean across all member workspaces.
    pub clean_all: bool,
    /// Clean only documentation artifacts (target/doc).
    pub clean_doc: bool,
    /// Clean release artifacts (target/release).
    pub clean_release: bool,
    /// Audit and report sizes without deleting files.
    pub dry_run: bool,
}

/// Options controlling age-based cache pruning.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PruneOpts {
    /// Delete test and build artifacts older than N days.
    pub keep_days: u32,
    /// Audit and report prune candidates without deleting.
    pub dry_run: bool,
}

impl Default for PruneOpts {
    fn default() -> Self {
        Self {
            keep_days: 3,
            dry_run: false,
        }
    }
}

/// Summary report returned after a clean or prune operation.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct CleanReport {
    /// Disk usage before operation.
    pub initial_usage: DiskUsage,
    /// Estimated or actual bytes reclaimed.
    pub reclaimed_bytes: u64,
    /// Target paths modified or removed.
    pub paths_removed: Vec<String>,
    /// Whether this was a dry run.
    pub dry_run: bool,
}
